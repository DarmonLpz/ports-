// ---- Land/See-Maske ----------------------------------------------------------
const MASK_W = 360, MASK_H = 180; // 1° Auflösung
let landMask = null;

function pointInPoly(lon, lat, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const xi = poly[i][0], yi = poly[i][1];
    const xj = poly[j][0], yj = poly[j][1];
    const hit = ((yi > lat) !== (yj > lat)) &&
      (lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi);
    if (hit) inside = !inside;
  }
  return inside;
}

export function buildLandMask() {
  if (landMask) return landMask;
  landMask = new Uint8Array(MASK_W * MASK_H);
  for (let y = 0; y < MASK_H; y++) {
    const lat = 90 - (y + 0.5);              // 89.5 .. -89.5
    for (let x = 0; x < MASK_W; x++) {
      const lon = (x + 0.5) - 180;           // -179.5 .. 179.5
      let land = 0;
      for (const c of CONTINENTS) {
        if (pointInPoly(lon, lat, c.poly)) { land = 1; break; }
      }
      landMask[y * MASK_W + x] = land;
    }
  }
  return landMask;
}

export function isLand(lat, lon) {
  if (!landMask) buildLandMask();
  lon = ((lon + 180) % 360 + 360) % 360 - 180;
  const x = Math.min(MASK_W - 1, Math.max(0, Math.floor(lon + 180)));
  const y = Math.min(MASK_H - 1, Math.max(0, Math.floor(90 - lat)));
  return landMask[y * MASK_W + x] === 1;
}

export const MASK = { W: MASK_W, H: MASK_H, get: () => buildLandMask() };
